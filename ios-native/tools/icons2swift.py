# Converts the Android app's icon table (android-native/.../ui/icons/IconData.kt, itself made from the prototype's
# sprite) into ios-native/METRX/Icons/IconData.swift, so both apps draw the same icons.
import re, sys, json
src = open(sys.argv[1], encoding="utf-8").read()
out = ["// Generated by ios-native/tools/icons2swift.py from the Android icon table. Do not edit by hand.", "",
       "let ICONS: [String: IconDef] = ["]
for m in re.finditer(r'"(\w+)" to IconDef\(([\d.]+)f, ([\d.]+)f, listOf\((.*?)\)\)(?:,\n|\n\))', src, re.S):
    name, w, h, body = m.groups()
    parts = []
    for p in re.finditer(r'IconPart\("([^"]*)"((?:, \w+ = [^,)]+)*)\)', body):
        d, rest = p.groups()
        kw = dict(re.findall(r'(\w+) = ("[^"]*"|[\d.]+f?)', rest))
        kw = {k: ("0" + v if v.startswith(".") else v) for k, v in kw.items()}
        args = [json.dumps(d)]
        if "fill" in kw: args.append("fill: " + kw["fill"])
        if "stroke" in kw: args.append("stroke: " + kw["stroke"])
        if "strokeWidth" in kw: args.append("strokeWidth: " + kw["strokeWidth"].rstrip("f"))
        if "opacity" in kw: args.append("opacity: " + kw["opacity"].rstrip("f"))
        parts.append("IconPart(" + ", ".join(args) + ")")
    out.append(f'    "{name}": IconDef(w: {w}, h: {h}, parts: [' + ", ".join(parts) + "]),")
out.append("]")
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(len(out) - 4, "icons")
